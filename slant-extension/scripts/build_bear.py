#!/usr/bin/env python3
"""Copy extension/lib/bear.js (the Slant bear, an ES module) into content.js between the BEGIN/END bear.js markers.
Content scripts cannot `import`, and the manifest exposes no web-accessible files, so the bear is inlined at build time.
lib/bear.js is the only place to edit the bear; tests/test_extension.mjs fails if content.js holds a stale copy.
Run: python scripts/build_bear.py"""
import os, re, sys
EXT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "extension")
BEGIN, END = "  // BEGIN bear.js (generated by scripts/build_bear.py from lib/bear.js; do not edit here)\n", "  // END bear.js\n"

def block():
    src = open(os.path.join(EXT, "lib", "bear.js"), encoding="utf-8").read()
    body = re.sub(r"^export ", "", src, flags=re.M)
    body = "\n".join(("    " + l) if l.strip() else "" for l in body.rstrip().split("\n"))
    return BEGIN + "  const Bear = (() => {\n" + body + "\n    return { compose, draw, scoresFromResult, aggregate, W, H };\n  })();\n" + END

def main():
    p = os.path.join(EXT, "content.js")
    s = open(p, encoding="utf-8").read()
    i, j = s.index(BEGIN), s.index(END) + len(END)
    new = s[:i] + block() + s[j:]
    if "--check" in sys.argv:
        sys.exit(0 if new == s else 1)
    open(p, "w", encoding="utf-8").write(new)
    print("content.js: bear.js block", "unchanged" if new == s else "updated")

if __name__ == "__main__":
    main()
