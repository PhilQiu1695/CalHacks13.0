"""Generates extension/lib/slant-core.js from Slant's live code: quote validation, timestamp mapping and score helpers are
copied verbatim (not re-implemented) and the display constants come from spec/slant_spec.json."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FUNCS = ["fmtT", "norm", "buildIndex", "segAt", "findNear", "locate", "leanScore", "leanBand", "fmtLean", "biasWord"]
CONSTS = ["clamp", "asArr", "LEAN_MAX", "LEAN_COLS"]


def extract_function(code, name):
    m = re.search(r"^function " + re.escape(name) + r"\(", code, re.M)
    if not m:
        raise SystemExit("function not found: " + name)
    i, depth, started = m.start(), 0, False
    for j in range(code.index("{", m.end()), len(code)):
        c = code[j]
        if c == "{":
            depth += 1
            started = True
        elif c == "}":
            depth -= 1
            if started and depth == 0:
                return code[i:j + 1]
    raise SystemExit("unbalanced: " + name)


def extract_const(code, name):
    m = re.search(r"^const " + re.escape(name) + r" = .*$", code, re.M)
    if not m:
        raise SystemExit("const not found: " + name)
    return m.group(0)


def main():
    code = open(os.path.join(ROOT, "reference", "slant-app.jsx")).read()
    spec = json.load(open(os.path.join(ROOT, "spec", "slant_spec.json")))
    out = ["// GENERATED by scripts/build_core.py from Slant's live code (apps/slant/app). Do not edit by hand.",
           "// Quote validation, timestamp mapping and score helpers are copied verbatim so the panel matches the app.", ""]
    for k in ("DIMS", "SRC_LABEL", "LEAN_BANDS", "SLANT_EXPLAINER", "MODEL"):
        out.append(f"export const {k} = {json.dumps(spec[k], ensure_ascii=False)};")
    out.append("")
    out += [extract_const(code, c) for c in CONSTS]
    out += [extract_function(code, f) for f in FUNCS]
    out.append("")
    out.append("export { " + ", ".join(CONSTS + FUNCS) + " };")
    open(os.path.join(ROOT, "extension", "lib", "slant-core.js"), "w").write("\n".join(out) + "\n")
    print("slant-core.js written:", ", ".join(CONSTS + FUNCS))


if __name__ == "__main__":
    main()
